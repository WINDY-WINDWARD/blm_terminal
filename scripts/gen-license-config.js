// Bakes production license config at build time (Step 4).
// Usage: BAKED_LICENSE_URL=https://... BAKED_BOX_KID=box-1 BAKED_ENC_PUB=... \
//   BAKED_LEASE_PUBS=pub1,pub2 BAKED_FEED_URL=https://... BAKED_OTA_PUBS=... \
//   node scripts/gen-license-config.js
// Output electron/licenseConfig.js is gitignored. Dev builds fall back to env.
const fs = require('fs');
const path = require('path');

const cfg = {
  url: process.env.BAKED_LICENSE_URL || '',
  boxKid: process.env.BAKED_BOX_KID || 'box-1',
  encPub: process.env.BAKED_ENC_PUB || '',
  leasePubs: (process.env.BAKED_LEASE_PUBS || '').split(',').map((s) => s.trim()).filter(Boolean),
  feedUrl: process.env.BAKED_FEED_URL || '',
  otaPubs: (process.env.BAKED_OTA_PUBS || '').split(',').map((s) => s.trim()).filter(Boolean),
};

const out = `'use strict';\n// AUTO-GENERATED by scripts/gen-license-config.js — do not edit.\nmodule.exports = ${JSON.stringify(cfg, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'electron', 'licenseConfig.js'), out);
console.log(`baked license config (url set: ${!!cfg.url}, lease pubs: ${cfg.leasePubs.length}, ota pubs: ${cfg.otaPubs.length})`);
